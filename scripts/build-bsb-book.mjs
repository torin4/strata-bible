#!/usr/bin/env node
// Generator: emit `content/bsb-<book>.ts`, a full-text lookup for one book of the Berean
// Standard Bible (BSB, public domain / CC0). The reader uses it to reveal the verses a curated
// sitting leaves out ("Read the full text"), without ever bundling a licensed translation.
// Source is the same authoritative file the scripture migration used: bereanbible.com/bsb.txt
// ("Book C:V\ttext", one verse per line).
//
// Usage:  node scripts/build-bsb-book.mjs <Book> <expectedVerses> [path/to/bsb.txt]
//   e.g.  node scripts/build-bsb-book.mjs Genesis 1533
//         node scripts/build-bsb-book.mjs Exodus 1213
//   Download first if needed:  curl -s -o /tmp/bsb.txt https://bereanbible.com/bsb.txt
//
// The expected verse count is required, not optional: it is the one cheap guard against a
// truncated or half-downloaded source producing a plausible-looking file. A book whose count
// does not match refuses to emit.
import { readFileSync, writeFileSync } from "node:fs";

const [book, expectedRaw, srcArg] = process.argv.slice(2);
const SRC = srcArg ?? "/tmp/bsb.txt";

if (!book || !expectedRaw) {
  console.error(
    "Usage: node scripts/build-bsb-book.mjs <Book> <expectedVerses> [path/to/bsb.txt]",
  );
  process.exit(1);
}

const expected = Number(expectedRaw);
if (!Number.isInteger(expected) || expected <= 0) {
  console.error(
    `Expected verse count must be a positive integer, got "${expectedRaw}".`,
  );
  process.exit(1);
}

// Book names carry spaces and digits ("1 Samuel", "Song of Solomon"), so the reference matcher
// is built from the escaped name rather than a fixed pattern.
const escaped = book.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
const reference = new RegExp(`^${escaped} (\\d+):(\\d+)$`);

// "<Book> C:V" -> text, this book only.
const verses = [];
const seen = new Set();
for (const line of readFileSync(SRC, "utf8").split("\n")) {
  const tab = line.indexOf("\t");
  if (tab === -1) continue;
  const ref = line.slice(0, tab).trim();
  const m = ref.match(reference);
  if (!m) continue;
  const key = `${m[1]}:${m[2]}`;
  const text = line.slice(tab + 1).trim();
  if (!text || seen.has(key)) continue;
  seen.add(key);
  verses.push([Number(m[1]), Number(m[2]), key, text]);
}

// Refuse to emit a truncated or empty file.
if (verses.length !== expected) {
  console.error(
    `Expected ${expected} ${book} verses, got ${verses.length}. Is ${SRC} the full BSB?`,
  );
  process.exit(1);
}

verses.sort((a, b) => a[0] - b[0] || a[1] - b[1]);

// "Song of Solomon" -> bsb-song-of-solomon.ts / BSB_SONG_OF_SOLOMON.
const slug = book
  .toLowerCase()
  .replace(/[^a-z0-9]+/g, "-")
  .replace(/^-|-$/g, "");
const symbol = `BSB_${slug.toUpperCase().replace(/-/g, "_")}`;
const OUT = `content/bsb-${slug}.ts`;

const body = verses
  .map(
    ([, , key, text]) => `  ${JSON.stringify(key)}: ${JSON.stringify(text)},`,
  )
  .join("\n");

const file = `// GENERATED by scripts/build-bsb-book.mjs — do not edit by hand.
// The Berean Standard Bible (BSB) text of ${book}, public domain / CC0, keyed "chapter:verse".
// Source: bereanbible.com/bsb.txt. Used to reveal the verses a curated sitting omits; this
// is server-only data, kept out of the client bundle (see lib/expand.ts).
export const ${symbol}: Record<string, string> = {
${body}
};
`;

writeFileSync(OUT, file);
console.log(`Wrote ${OUT}: ${verses.length} ${book} verses.`);
