#!/usr/bin/env node
// One-off generator: emit `content/bsb-genesis.ts`, a full-text lookup for Genesis from
// the Berean Standard Bible (BSB, public domain / CC0). The reader uses it to reveal the
// verses a curated sitting leaves out ("Read the full text"), without ever bundling a
// licensed translation. Source is the same authoritative file the scripture migration
// used: bereanbible.com/bsb.txt ("Book C:V\ttext", one verse per line).
//
// Usage:  node scripts/build-bsb-genesis.mjs [path/to/bsb.txt]
//   Download first if needed:  curl -s -o /tmp/bsb.txt https://bereanbible.com/bsb.txt
import { readFileSync, writeFileSync } from "node:fs";

const SRC = process.argv[2] ?? "/tmp/bsb.txt";
const OUT = "content/bsb-genesis.ts";

// "Genesis C:V" -> text, Genesis only.
const verses = [];
const seen = new Set();
for (const line of readFileSync(SRC, "utf8").split("\n")) {
  const tab = line.indexOf("\t");
  if (tab === -1) continue;
  const ref = line.slice(0, tab).trim();
  const m = ref.match(/^Genesis (\d+):(\d+)$/);
  if (!m) continue;
  const key = `${m[1]}:${m[2]}`;
  const text = line.slice(tab + 1).trim();
  if (!text || seen.has(key)) continue;
  seen.add(key);
  verses.push([Number(m[1]), Number(m[2]), key, text]);
}

// Genesis has 1533 verses; refuse to emit a truncated or empty file.
if (verses.length !== 1533) {
  console.error(
    `Expected 1533 Genesis verses, got ${verses.length}. Is ${SRC} the full BSB?`,
  );
  process.exit(1);
}

verses.sort((a, b) => a[0] - b[0] || a[1] - b[1]);

const body = verses
  .map(
    ([, , key, text]) => `  ${JSON.stringify(key)}: ${JSON.stringify(text)},`,
  )
  .join("\n");

const file = `// GENERATED by scripts/build-bsb-genesis.mjs — do not edit by hand.
// The Berean Standard Bible (BSB) text of Genesis, public domain / CC0, keyed "chapter:verse".
// Source: bereanbible.com/bsb.txt. Used to reveal the verses a curated sitting omits; this
// is server-only data, kept out of the client bundle (see lib/expand.ts).
export const BSB_GENESIS: Record<string, string> = {
${body}
};
`;

writeFileSync(OUT, file);
console.log(`Wrote ${OUT}: ${verses.length} Genesis verses.`);
